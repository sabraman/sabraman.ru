export type Variant = "baseline" | "fewshot" | "plan" | "critique";

export const VARIANTS: Variant[] = ["baseline", "fewshot", "plan", "critique"];

export const VARIANT_LABEL: Record<Variant, string> = {
	baseline: "базовый",
	fewshot: "примеры тона",
	plan: "сначала план",
	critique: "черновик и правка",
};

const EXEMPLARS = `Менеджер присылает отчёт в полночь. Не потому что медленный. Потому что собирает его руками из трёх мест, и по-другому пока никак.

Просят «личный кабинет». Открываю, как работают сейчас: пять таблиц, две группы в вотсапе и один человек, который всё помнит. Кабинет тут не нужен.

Автоматизация ничего не ускоряет. Она убирает конкретное действие. Пока действие не названо, ускорять нечего.`;

export function variantBlock(variant: Variant): string {
	if (variant === "baseline") return "";

	if (variant === "fewshot") {
		return [
			"## Как звучит автор",
			"Три примера интонации. Это не факты и не шаблоны — только ритм, длина фраз и способ думать.",
			"",
			EXEMPLARS,
			"",
			"Не пересказывай их и не бери их содержание. Напиши так же плотно, но про свою тему.",
		].join("\n");
	}

	if (variant === "plan") {
		return [
			"## Порядок работы",
			"1. В поле `notes` сначала зафиксируй четыре вещи: одну мысль поста, конкретную сцену из работы, зачем это читателю, и что ты выкинул как лишнее.",
			"2. Только потом напиши текст.",
			"3. В `body` — готовый пост без плана, без пояснений и без следов черновика.",
		].join("\n");
	}

	return [
		"## Порядок работы",
		"1. Напиши черновик.",
		"2. Проверь его по шести пунктам: первая строка цепляет; в посте ровно одна мысль; есть конкретная сцена, а не общие слова; нет выдуманных цифр; нет канцелярита; последний абзац не лишний.",
		"3. Перепиши с учётом проверки.",
		"4. В `notes` — что именно исправил. В `body` — только финальный текст.",
	].join("\n");
}
